// @vitest-environment jsdom
import { afterEach, expect, it, vi } from "vitest";
import { cleanup, fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import "@testing-library/jest-dom/vitest";
import { SourceControls, sourceStatusText } from "./SourceControls";
import { ConnectApp } from "./ConnectApp";
import { bridgeFor, selected } from "./test-fixtures";
import type { ConnectStatus, SourceSubscriptionStatus } from "./types";
afterEach(cleanup);
const source: SourceSubscriptionStatus = { id: "source_one", sourceProfile: "packproof.order-lines/v1", displayName: "Order exports", state: "approved", localPaused: true, configurationRevision: 1, grantRevision: 2, queue: {}, folder: "Approved export folder", files: [{ name: "orders.csv", byteSize: 123 }], selectedFileName: "orders.csv", fileSha256: "a".repeat(64), headers: ["Order", "Line", "Quantity"], rowCount: 1, samples: [{ Order: "0010482", Line: "004", Quantity: "10" }] };
const current: ConnectStatus = { ...selected, sourceSubscriptions: [source], capabilities: { ...selected.capabilities!, typedSourceSubscriptions: true } };
const run = async (_message: string, operation: () => Promise<ConnectStatus>) => { await operation(); };
it("gates the new source home while preserving legacy setup", async () => {
  const bridge = bridgeFor(current);
  const app = render(<ConnectApp bridge={bridge}/>);
  await screen.findByRole("heading", { name: "Your sources" });
  expect(screen.getByRole("article", { name: "Order exports" })).toBeVisible();
  fireEvent.click(screen.getByRole("button", { name: "Manage the existing shipment connection" }));
  expect(screen.getByRole("heading", { name: "Does this shipment look right?" })).toBeVisible();
  app.unmount();
  render(<ConnectApp bridge={bridgeFor({ ...current, capabilities: selected.capabilities })}/>);
  await screen.findByRole("heading", { name: "Does this shipment look right?" });
  expect(screen.queryByRole("article", { name: "Order exports" })).toBeNull();
});
it("inspects locally and requires whole-original consent for the exact selected file", async () => {
  const bridge = bridgeFor(current);
  render(<SourceControls status={current} bridge={bridge} disabled={false} action={run} external={() => {}}/>);
  const card = within(screen.getByRole("article", { name: "Order exports" }));
  const preview = card.getByRole("button", { name: "Preview this exact report" });
  expect(preview).toBeDisabled();
  expect(bridge.previewSubscription).not.toHaveBeenCalled();
  expect(card.getByText("0010482")).toBeInTheDocument();
  fireEvent.change(card.getByLabelText("Completed report"), { target: { value: "orders.csv" } });
  await waitFor(() => expect(bridge.inspectSubscriptionFile).toHaveBeenCalledWith({ id: "source_one", fileName: "orders.csv" }));
  expect(bridge.previewSubscription).not.toHaveBeenCalled();
  fireEvent.click(card.getByRole("checkbox", { name: /Upload and preserve this entire original/ }));
  fireEvent.click(preview);
  await waitFor(() => expect(bridge.previewSubscription).toHaveBeenCalledWith({ id: "source_one", fileName: "orders.csv", wholeFileUploadApproved: true }));
});
it("does not equate a queued batch with a verified case or recurring collection", () => {
  const state = { ...current, sourceSubscriptions: [{ ...source, receipt: { id: "batch_one", state: "queued", counts: { processing: 1 } } }] };
  const bridge = bridgeFor(state);
  render(<SourceControls status={state} bridge={bridge} disabled={false} action={run} external={() => {}}/>);
  expect(screen.queryByRole("button", { name: "Approve recurring collection" })).toBeNull();
  expect(screen.queryByRole("button", { name: "Open first case" })).toBeNull();
  fireEvent.click(screen.getByRole("button", { name: "Check receipt and first case" }));
  expect(bridge.verifySubscription).toHaveBeenCalledWith("source_one");
});
it("requires separate exact-batch approval and resets consent on source revision", () => {
  const state = { ...current, sourceSubscriptions: [{ ...source, receipt: { id: "batch_one", state: "previewed", counts: { valid: 1, rejected: 0 } } }] };
  const bridge = bridgeFor(state);
  const view = render(<SourceControls status={state} bridge={bridge} disabled={false} action={run} external={() => {}}/>);
  expect(screen.getByRole("button", { name: "Import reviewed batch" })).toBeDisabled();
  fireEvent.click(screen.getByRole("checkbox", { name: /Import this exact previewed batch/ }));
  fireEvent.click(screen.getByRole("button", { name: "Import reviewed batch" }));
  expect(bridge.commitSubscription).toHaveBeenCalledWith({ id: "source_one", wholeBatchApproved: true });
  view.rerender(<SourceControls status={{ ...state, sourceSubscriptions: state.sourceSubscriptions.map(s => ({ ...s, configurationRevision: 2 })) }} bridge={bridge} disabled={false} action={run} external={() => {}}/>);
  expect(screen.getByRole("button", { name: "Import reviewed batch" })).toBeDisabled();
});
it("retains source-local error and pause states without claiming completeness", () => {
  expect(sourceStatusText({ ...source, state: "active", localPaused: false, lastErrorCode: "MAPPING_NEEDS_REVIEW" })).toBe("Report changed — review needed");
  expect(sourceStatusText({ ...source, lastErrorCode: "NETWORK_UNAVAILABLE" })).toBe("Source delayed or offline");
  const state = { ...current, sourceSubscriptions: [{ ...source, state: "revoked" }, { ...source, id: "source_two", displayName: "Loading exports", state: "active", localPaused: false }] };
  const bridge = bridgeFor(state);
  render(<SourceControls status={state} bridge={bridge} disabled={false} action={run} external={() => {}}/>);
  expect(within(screen.getByRole("article", { name: "Order exports" })).queryByRole("button")).toBeNull();
  fireEvent.click(within(screen.getByRole("article", { name: "Loading exports" })).getByRole("button", { name: "Pause this source" }));
  expect(bridge.pauseSubscription).toHaveBeenCalledWith("source_two");
  expect(screen.getAllByText("Coverage unknown")).toHaveLength(2);
});
it("starts source setup with a native folder chooser and no raw configuration entry", () => {
  const bridge = bridgeFor(current);
  render(<SourceControls status={current} bridge={bridge} disabled={false} action={run} external={() => {}}/>);
  fireEvent.click(screen.getByRole("button", { name: "Add an existing export source" }));
  fireEvent.click(screen.getByRole("button", { name: "Choose new source folder" }));
  expect(bridge.chooseNewSubscriptionFolder).toHaveBeenCalledWith();
  expect(screen.queryByRole("textbox", { name: /JSON|API key|folder digest/i })).toBeNull();
  expect(bridge.proposeSubscription).not.toHaveBeenCalled();
});
it("submits a reviewed source mapping and an explicit UTC history policy from ordinary form controls", () => {
  const state: ConnectStatus = { ...current, subscriptionDraft: { folder: "New approved export folder", folderDigest: "b".repeat(64), selectedFileName: "new-orders.csv", fileSha256: "c".repeat(64), files: [{ name: "new-orders.csv", byteSize: 300 }], headers: ["Row", "Revision", "Order", "Line", "Qty", "Unit"], rowCount: 1 } };
  const bridge = bridgeFor(state);
  render(<SourceControls status={state} bridge={bridge} disabled={false} action={run} external={() => {}}/>);
  fireEvent.click(screen.getByRole("button", { name: "Add an existing export source" }));
  const form = within(screen.getByRole("region", { name: "Add source" }));
  fireEvent.change(form.getByLabelText("Source name"), { target: { value: "ERP orders" } });
  fireEvent.change(form.getByLabelText("Reference group"), { target: { value: "site-a-qualified" } });
  for (const [label, value] of [["Stable source row or event ID", "Row"], ["Source revision", "Revision"], ["Order number", "Order"], ["Stable order line ID", "Line"], ["Quantity", "Qty"], ["Unit", "Unit"]]) fireEvent.change(form.getByLabelText(label), { target: { value } });
  const semantic = form.getAllByLabelText("Or a meaning confirmed for every row");
  for (const [index, value] of ["snapshot", "orderedQuantity", "unknown"].entries()) fireEvent.change(semantic[index], { target: { value } });
  fireEvent.change(form.getByLabelText("Approved history starts at (UTC)"), { target: { value: "2026-11-14T00:00" } });
  fireEvent.change(form.getByLabelText("Records without a source time"), { target: { value: "retain_unknown" } });
  const save = form.getByRole("button", { name: "Save source for browser approval" });
  expect(save).toBeDisabled();
  fireEvent.click(form.getByRole("checkbox", { name: /I reviewed the exact report/ }));
  expect(save).toBeEnabled();
  fireEvent.click(save);
  expect(bridge.proposeSubscription).toHaveBeenCalledWith(expect.objectContaining({ displayName: "ERP orders", sourceNamespace: "site-a-qualified", historyFrom: "2026-11-14T00:00:00Z", unknownTimePolicy: "retain_unknown", constants: { observationKind: "snapshot", property: "orderedQuantity", timeQuality: "unknown" }, wholeFileUploadApproved: true }));
  expect(bridge.previewSubscription).not.toHaveBeenCalled();
});
it("reviews composite source keys and source-as-of versions without JSON or invented row IDs", () => {
  const state: ConnectStatus = { ...current, capabilities: { ...current.capabilities!, typedSourceBatchSchemas: ["packproof.typed-source-batch/v1", "packproof.typed-source-batch/v2"] }, subscriptionDraft: { folder: "Approved exports", folderDigest: "b".repeat(64), selectedFileName: "orders.csv", fileSha256: "c".repeat(64), files: [{ name: "orders.csv", byteSize: 300 }], headers: ["Order", "Line", "Qty", "Unit", "AsOf"], rowCount: 1 } };
  const bridge = bridgeFor(state);
  render(<SourceControls status={state} bridge={bridge} disabled={false} action={run} external={() => {}}/>);
  fireEvent.click(screen.getByRole("button", { name: "Add an existing export source" }));
  const form = within(screen.getByRole("region", { name: "Add source" }));
  fireEvent.change(form.getByLabelText("Source name"), { target: { value: "ERP snapshots" } });
  fireEvent.change(form.getByLabelText("Reference group"), { target: { value: "qualified-erp" } });
  fireEvent.click(form.getByRole("checkbox", { name: "Review an explicit source identity and revision policy" }));
  fireEvent.change(form.getByLabelText("Source row identity"), { target: { value: "composite" } });
  fireEvent.change(form.getByLabelText("Revision basis"), { target: { value: "source_as_of" } });
  for (const [label, value] of [["Order number", "Order"], ["Stable order line ID", "Line"], ["Quantity", "Qty"], ["Unit", "Unit"], ["Snapshot as of time with offset", "AsOf"]]) fireEvent.change(form.getByRole("combobox", { name: label }), { target: { value } });
  const semantic = form.getAllByLabelText("Or a meaning confirmed for every row");
  for (const [index, value] of ["snapshot", "orderedQuantity", "snapshot_time_only"].entries()) fireEvent.change(semantic[index], { target: { value } });
  fireEvent.change(form.getByLabelText("Approved history starts at (UTC)"), { target: { value: "2026-11-14T00:00" } });
  for (const label of ["Order number", "Reported value meaning"]) fireEvent.click(form.getByRole("checkbox", { name: label }));
  fireEvent.click(form.getByRole("checkbox", { name: /I reviewed the exact report/ }));
  const save = form.getByRole("button", { name: "Save source for browser approval" });
  expect(save).toBeDisabled();
  fireEvent.click(form.getByRole("checkbox", { name: "Stable order line ID" }));
  expect(save).toBeDisabled(); // Every policy edit invalidates whole-original review.
  fireEvent.click(form.getByRole("checkbox", { name: /I reviewed the exact report/ }));
  expect(save).toBeEnabled();fireEvent.click(save);
  expect(bridge.proposeSubscription).toHaveBeenCalledWith(expect.objectContaining({ batchSchema: "packproof.typed-source-batch/v2", identityPolicy: { schema: "packproof.source-identity-policy/v1", eventKey: { kind: "composite", fields: ["orderId", "orderLineId", "property"] }, revision: { kind: "source_as_of" } } }));
  expect(form.queryByRole("textbox", { name: /JSON|API key/i })).toBeNull();
});
